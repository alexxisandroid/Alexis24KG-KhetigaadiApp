package com.khetigaadi.implement.compare.model;
public class ImplResult {
    private int id;
    private String rightSideValue, leftSideValue, Label;
    public int getId() {
        return id;
    }
    public void setId(int id) {
        this.id = id;
    }
    public String getRightSideValue() {
        return rightSideValue;
    }
    public void setRightSideValue(String rightSideValue) {
        this.rightSideValue = rightSideValue;
    }
    public String getLeftSideValue() {
        return leftSideValue;
    }
    public void setLeftSideValue(String leftSideValue) {
        this.leftSideValue = leftSideValue;
    }
    public String getLabel() {
        return Label;
    }
    public void setLabel(String label) {
        Label = label;
    }
}
